package nextflow.script.control;

import java.util.List;
import java.util.stream.Stream;

import nextflow.script.ast.ProcessNodeV2;
import nextflow.script.ast.ScriptNode;
import nextflow.test.TestUtils;
import org.codehaus.groovy.ast.expr.ClosureExpression;
import org.codehaus.groovy.ast.expr.Expression;
import org.codehaus.groovy.ast.expr.MethodCallExpression;
import org.codehaus.groovy.ast.expr.TupleExpression;
import org.codehaus.groovy.ast.stmt.BlockStatement;
import org.codehaus.groovy.ast.stmt.ExpressionStatement;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.params.provider.Arguments.arguments;

/**
 * Specifies the implicit stagers generated by {@link ImplicitStagers} for process inputs.
 *
 * @author Ben Sherman <bentshermann@gmail.com>
 */
class ImplicitStagersTest {

    static Stream<Arguments> processInputs() {
        var vcfsTargets = List.of(
            "vcfs*.vcf?.findAll({ java.lang.Object p -> ... })",
            "vcfs*.tbi?.findAll({ java.lang.Object p -> ... })",
            "vcfs*.extra?.collectMany({ java.lang.Object e -> ... })");
        return Stream.of(
            arguments("x: Integer", List.of()),
            arguments("vcf: Path", List.of("vcf")),
            arguments("vcf: Path?", List.of("vcf")),
            arguments("vcfs: List<Path>", List.of("vcfs")),
            arguments("vcfs: Set<Path>", List.of("vcfs")),
            arguments("record(id: String, vcf: Path)", List.of("vcf")),
            arguments("vcf: Vcf", List.of("vcf?.vcf", "vcf?.tbi", "vcf?.extra")),
            arguments("vcf: Vcf?", List.of("vcf?.vcf", "vcf?.tbi", "vcf?.extra")),
            arguments("vcfs: List<Vcf>", vcfsTargets),
            arguments("record(id: String, vcfs: List<Vcf>)", vcfsTargets),
            arguments("cohorts: List<Cohort>", List.of(
                "cohorts*.vcfs?.collectMany({ java.lang.Object e -> ... })*.vcf?.findAll({ java.lang.Object p -> ... })",
                "cohorts*.vcfs?.collectMany({ java.lang.Object e -> ... })*.tbi?.findAll({ java.lang.Object p -> ... })",
                "cohorts*.vcfs?.collectMany({ java.lang.Object e -> ... })*.extra?.collectMany({ java.lang.Object e -> ... })"))
        );
    }

    @ParameterizedTest
    @MethodSource("processInputs")
    void generateImplicitStagersForProcessInputs(String declaration, List<String> expected) {
        var stagers = stagerTargets("""
            nextflow.enable.types = true

            record Vcf {
                id: String
                vcf: Path
                tbi: Path?
                extra: List<Path>
            }

            record Cohort {
                id: String
                vcfs: List<Vcf>
            }

            process CHECK {
                input:
                %s

                script:
                'true'
            }
            """.formatted(declaration));
        assertThat(stagers).isEqualTo(expected);
    }

    private static List<String> stagerTargets(String contents) {
        var parser = new ScriptParser();
        var source = parser.parse("main.nf", contents);
        parser.analyze();
        assertThat(TestUtils.getErrors(source)).isEmpty();

        // the stagers are the second statement of the process body
        var process = (ProcessNodeV2) ((ScriptNode) source.getAST()).getProcesses().get(0);
        var result = new ProcessToGroovyVisitorV2(source).transform(process);
        var processCall = (MethodCallExpression) ((ExpressionStatement) result).getExpression();
        var closure = (ClosureExpression) ((TupleExpression) processCall.getArguments()).getExpression(1);
        var stagers = (BlockStatement) ((BlockStatement) closure.getCode()).getStatements().get(1);
        return stagers.getStatements().stream()
            .map(st -> {
                var call = (MethodCallExpression) ((ExpressionStatement) st).getExpression();
                assertThat(call.getMethodAsString()).isEqualTo("stageAs");
                var target = (ClosureExpression) ((TupleExpression) call.getArguments()).getExpression(0);
                return closureBody(target).getText();
            })
            .toList();
    }

    private static Expression closureBody(ClosureExpression closure) {
        var code = closure.getCode();
        var st = code instanceof BlockStatement block ? block.getStatements().get(0) : code;
        return ((ExpressionStatement) st).getExpression();
    }

}
