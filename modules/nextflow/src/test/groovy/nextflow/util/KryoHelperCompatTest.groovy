package nextflow.util

import java.nio.file.Paths
import java.util.concurrent.TimeUnit
import java.util.concurrent.atomic.AtomicInteger

import com.esotericsoftware.kryo.KryoException
import groovy.transform.Canonical
import nextflow.processor.TaskStatus
import spock.lang.Specification
import spock.lang.Unroll
/**
 * Check the cache entries written by previous versions, i.e. {@code kryo-cache-golden.txt},
 * which was generated by serializing {@link #values()} with Nextflow 26.10
 */
class KryoHelperCompatTest extends Specification {

    @Canonical
    static class Sample {
        String id
        Integer size
        List<String> tags
    }

    static Map<String,Object> values() {
        def w = 'world'
        def result = new LinkedHashMap<String,Object>()
        result.string = 'hello'
        result.integer = 42
        result.long = 42L
        result.double = 1.5d
        result.bool = true
        result.bigDecimal = 1.25G
        result.bigInteger = 12345678901234567890G
        result.gstring = "hello $w"
        result.list = [1, 'two', 3.0d]
        result.map = [a: 1, b: [c: 'd']]
        result.hashSet = new HashSet(['x'])
        result.linkedSet = new LinkedHashSet(['x', 'y'])
        result.treeMap = new TreeMap([b: 2, a: 1])
        result.treeSet = new TreeSet(['b', 'a'])
        result.immutableList = [1, 2].asImmutable()
        result.immutableMap = [a: 1].asImmutable()
        result.immutableSet = (['a'] as Set).asImmutable()
        result.emptyList = Collections.emptyList()
        result.singletonList = Collections.singletonList('a')
        result.listOf = List.of(1, 2)
        result.mapOf = Map.of('a', 1)
        result.arraysAsList = Arrays.asList('a', 'b')
        result.path = Paths.get('/some/file.txt')
        result.file = new File('/some/file.txt')
        result.url = new URL('http://host.com/a.txt')
        result.uri = new URI('http://host.com/a.txt?x=1#y')
        result.uuid = UUID.fromString('b4f2a2b6-5f0f-4a6e-9a3a-1c1f0e7a6c11')
        result.pattern = ~/a.*b/
        result.duration = Duration.of('1h')
        result.memory = MemoryUnit.of('2 GB')
        result.tuple = new ArrayTuple(['a', 1])
        result.record = new RecordMap([id: 'x', n: 1])
        result.entry = [k: 'v'].entrySet().first()
        result.taskStatus = TaskStatus.COMPLETED
        result.timeUnit = TimeUnit.SECONDS
        result.intArray = [1, 2] as int[]
        result.stringArray = ['a', 'b'] as String[]
        result.objectArray = ['a', 1] as Object[]
        result.date = new Date(1000)
        result.sample = new Sample('s1', 10, ['a'])
        result.range = 1..3
        result.atomic = new AtomicInteger(5)
        return result
    }

    static Map<String,byte[]> golden() {
        final result = new LinkedHashMap<String,byte[]>()
        final text = KryoHelperCompatTest.class.getResourceAsStream('/nextflow/util/kryo-cache-golden.txt').text
        for( String line : text.readLines() ) {
            final p = line.indexOf('=')
            result.put(line.substring(0,p), line.substring(p+1).decodeBase64())
        }
        return result
    }

    // types without a no-arg constructor, which cannot be read back
    static final List<String> NOT_READABLE = ['listOf', 'mapOf', 'arraysAsList', 'range']

    // types read as a different implementation
    static final List<String> NORMALISED = ['entry']

    @Unroll
    def 'should read #name written by a previous version' () {
        given:
        def expected = values().get(name)
        def bytes = golden().get(name)

        when:
        def result = KryoHelper.deserialize(bytes)
        then:
        name in ['pattern', 'atomic'] ? result.toString() == expected.toString() : result == expected
        name in NORMALISED || result.getClass() == expected.getClass()

        where:
        name << values().keySet().findAll { it !in NOT_READABLE }
    }

    @Unroll
    def 'should write #name in the same format as a previous version' () {
        expect:
        KryoHelper.serialize(values().get(name)) == golden().get(name)

        where:
        name << values().keySet()
    }

    @Unroll
    def 'should fail to read #name written by a previous version' () {
        when:
        KryoHelper.deserialize(golden().get(name))
        then:
        def e = thrown(KryoException)
        e.message.contains('missing no-arg constructor')

        where:
        name << NOT_READABLE
    }
}
